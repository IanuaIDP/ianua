//! Sorting, reusable, multi-field ordering for list queries.
//!
//! A [`SortField`] names what a resource can be ordered by, and the word a
//! caller uses for it. A [`SortOrder`] is a non-empty, de-duplicated sequence
//! of those terms, parsed from a compact query string such as
//! `created_at,-display_name`:
//!
//! - comma separates terms, applied left to right (primary key first);
//! - a leading `-` means descending, a leading `+` (or nothing) means ascending;
//! - an unknown word is rejected with [`InvalidSort`] rather than ignored;
//! - a repeated field keeps its first occurrence, so the order stays total.
//!
//! This is the order a use case asks for, not how a store produces it: which
//! column a field reads and how the query is written belong to the adapter.

use std::cmp::Ordering;
use std::fmt;

use ianua_domain::message;

/// Direction of an ordered list query.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum SortDirection {
    /// Ascending order, the default for an explicitly named field.
    #[default]
    Asc,
    /// Descending order.
    Desc,
}

impl SortDirection {
    /// `ordering` as this direction reads it: kept for ascending, reversed
    /// for descending.
    #[must_use]
    pub fn apply(self, ordering: Ordering) -> Ordering {
        match self {
            Self::Asc => ordering,
            Self::Desc => ordering.reverse(),
        }
    }
}

/// A field a resource can be ordered by.
///
/// Implementors are normally generated by
/// [`define_sort_field!`](crate::define_sort_field), which ties each variant
/// to the word a caller sends for it.
pub trait SortField: Copy + Eq + Sized + 'static {
    /// The word a caller uses for this field in a sort query.
    fn token(self) -> &'static str;

    /// Resolves a query word to a field, or `None` if it names none.
    fn parse(token: &str) -> Option<Self>;

    /// The field used when a request does not specify one.
    fn default_field() -> Self;

    /// Every sortable field, for documentation and error messages.
    fn variants() -> &'static [Self];

    /// The default direction applied to the default field.
    ///
    /// Time-ordered resources override this to `Desc` for newest-first.
    #[must_use]
    fn default_direction() -> SortDirection {
        SortDirection::Asc
    }

    /// The words accepted by [`SortOrder::parse`].
    #[must_use]
    fn allowed_tokens() -> Vec<&'static str> {
        Self::variants().iter().map(|f| f.token()).collect()
    }
}

/// A single ordering term: a field paired with a direction.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Sort<F: SortField> {
    field: F,
    direction: SortDirection,
}

impl<F: SortField> Sort<F> {
    /// Creates an ordering term from a field and direction.
    #[must_use]
    pub fn new(field: F, direction: SortDirection) -> Self {
        Self { field, direction }
    }

    /// An ascending term on `field`.
    #[must_use]
    pub fn ascending(field: F) -> Self {
        Self::new(field, SortDirection::Asc)
    }

    /// A descending term on `field`.
    #[must_use]
    pub fn descending(field: F) -> Self {
        Self::new(field, SortDirection::Desc)
    }

    /// The field this term orders by.
    #[must_use]
    pub fn field(self) -> F {
        self.field
    }

    /// The direction of this term.
    #[must_use]
    pub fn direction(self) -> SortDirection {
        self.direction
    }
}

/// A non-empty, de-duplicated ordering over one or more [`Sort`] terms.
///
/// Always carries at least the default term, so list queries have a total,
/// stable order for pagination even when the caller supplies nothing.
#[derive(Debug, Clone)]
pub struct SortOrder<F: SortField> {
    terms: Vec<Sort<F>>,
}

impl<F: SortField> SortOrder<F> {
    /// A single-term ordering.
    #[must_use]
    pub fn single(term: Sort<F>) -> Self {
        Self { terms: vec![term] }
    }

    /// Parses a comma-separated ordering, falling back to the default when
    /// `input` is absent or blank.
    ///
    /// # Errors
    ///
    /// Returns [`InvalidSort`] if any token names no sortable column.
    pub fn parse(input: Option<&str>) -> Result<Self, InvalidSort> {
        let Some(raw) = input.map(str::trim).filter(|s| !s.is_empty()) else {
            return Ok(Self::default());
        };

        let mut terms: Vec<Sort<F>> = Vec::new();
        for token in raw.split(',').map(str::trim).filter(|t| !t.is_empty()) {
            let term: Sort<F> = parse_term(token)?;
            if terms.iter().any(|t| t.field == term.field) {
                continue;
            }
            terms.push(term);
        }

        if terms.is_empty() {
            return Ok(Self::default());
        }
        Ok(Self { terms })
    }

    /// The ordered terms, primary key first.
    #[must_use]
    pub fn terms(&self) -> &[Sort<F>] {
        &self.terms
    }
}

impl<F: SortField> Default for SortOrder<F> {
    fn default() -> Self {
        Self::single(Sort::new(F::default_field(), F::default_direction()))
    }
}

/// The order as the query string [`SortOrder::parse`] reads back, such as
/// `-created_at,name`. A [`Cursor`](crate::listing::Cursor) keeps it to know
/// which order it was made for.
impl<F: SortField> fmt::Display for SortOrder<F> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let words: Vec<String> = self.terms.iter().map(ToString::to_string).collect();
        f.write_str(&words.join(","))
    }
}

/// The term as one word of a sort query: the field, after a `-` when it
/// descends.
impl<F: SortField> fmt::Display for Sort<F> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.direction {
            SortDirection::Asc => f.write_str(self.field.token()),
            SortDirection::Desc => write!(f, "-{}", self.field.token()),
        }
    }
}

fn parse_term<F: SortField>(token: &str) -> Result<Sort<F>, InvalidSort> {
    let (direction, name) = split_direction(token);
    let Some(field) = F::parse(name) else {
        return Err(InvalidSort::new(name, F::allowed_tokens()));
    };
    Ok(Sort::new(field, direction))
}

/// The direction a token's sign asks for, and the name after it.
fn split_direction(token: &str) -> (SortDirection, &str) {
    if let Some(name) = token.strip_prefix('-') {
        return (SortDirection::Desc, name);
    }
    (SortDirection::Asc, token.strip_prefix('+').unwrap_or(token))
}

/// A sort token that names no sortable column.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("unknown sort field '{token}'; allowed: {}", allowed.join(", "))]
pub struct InvalidSort {
    token: String,
    allowed: Vec<&'static str>,
}

impl InvalidSort {
    fn new(token: &str, allowed: Vec<&'static str>) -> Self {
        Self {
            token: token.to_owned(),
            allowed,
        }
    }

    /// The rejected token.
    #[must_use]
    pub fn token(&self) -> &str {
        &self.token
    }
}

impl From<InvalidSort> for ianua_domain::shared::errors::DomainError {
    /// The refusal of the token, under its message key, naming the columns allowed.
    fn from(invalid: InvalidSort) -> Self {
        let token = &invalid.token;
        Self::invalid(message!(
            "app-unknown-sort-field-allowed",
            format!(
                "unknown sort field '{token}'; allowed: {}",
                invalid.allowed.join(", ")
            )
        ))
    }
}

/// Defines a [`SortField`] enum and its mapping in one place.
///
/// Each variant binds to the word a caller sends for it. Exactly one variant
/// is marked the default; an optional `default direction = Desc;` flips
/// newest-first ordering.
///
/// ```
/// use ianua_app::define_sort_field;
///
/// define_sort_field! {
///     /// Field a widget listing can be ordered by.
///     pub enum WidgetSortField {
///         /// Order by creation time.
///         CreatedAt => "created_at",
///         /// Order by name.
///         Name => "name",
///     }
///     default = CreatedAt;
///     default direction = Desc;
/// }
/// ```
#[macro_export]
macro_rules! define_sort_field {
    (
        $(#[$meta:meta])*
        $vis:vis enum $name:ident {
            $(
                $(#[$vmeta:meta])*
                $variant:ident => $token:literal
            ),+ $(,)?
        }
        default = $default:ident;
        $(default direction = $direction:ident;)?
    ) => {
        $(#[$meta])*
        #[derive(Debug, Clone, Copy, PartialEq, Eq)]
        $vis enum $name {
            $(
                $(#[$vmeta])*
                $variant,
            )+
        }

        impl $crate::listing::SortField for $name {
            fn token(self) -> &'static str {
                match self {
                    $( Self::$variant => $token, )+
                }
            }

            fn parse(token: &str) -> ::core::option::Option<Self> {
                match token {
                    $( $token => ::core::option::Option::Some(Self::$variant), )+
                    _ => ::core::option::Option::None,
                }
            }

            fn default_field() -> Self {
                Self::$default
            }

            fn variants() -> &'static [Self] {
                &[ $( Self::$variant, )+ ]
            }

            $(
                fn default_direction() -> $crate::listing::SortDirection {
                    $crate::listing::SortDirection::$direction
                }
            )?
        }
    };
}

#[cfg(test)]
mod tests {
    use super::*;

    define_sort_field! {
        /// Test field with a descending default.
        enum Field {
            /// Order by creation time.
            CreatedAt => "created_at",
            /// Order by name.
            Name => "name",
        }
        default = CreatedAt;
        default direction = Desc;
    }

    fn parsed(input: Option<&str>) -> Vec<Sort<Field>> {
        SortOrder::<Field>::parse(input).unwrap().terms().to_vec()
    }

    /// Ann asks for a listing without saying how to sort it. It comes newest
    /// first, the listing's own default.
    #[test]
    fn absent_input_uses_default_field_and_direction() {
        assert_eq!(parsed(None), [Sort::descending(Field::CreatedAt)]);
    }

    /// A sort made only of spaces counts as no sort, so the default applies.
    #[test]
    fn blank_input_uses_default() {
        assert_eq!(parsed(Some("   ")), [Sort::descending(Field::CreatedAt)]);
    }

    /// Ann sorts by name without a sign. The listing goes from A to Z.
    #[test]
    fn explicit_field_defaults_to_ascending() {
        assert_eq!(parsed(Some("name")), [Sort::ascending(Field::Name)]);
    }

    /// A minus in front of the field sorts it from Z to A.
    #[test]
    fn minus_prefix_is_descending() {
        assert_eq!(parsed(Some("-name")), [Sort::descending(Field::Name)]);
    }

    /// A plus in front of the field sorts it from A to Z, and the plus is not
    /// read as part of the field's name.
    #[test]
    fn plus_prefix_is_ascending_and_names_the_field_without_the_sign() {
        assert_eq!(parsed(Some("+name")), [Sort::ascending(Field::Name)]);
    }

    /// Ann sorts by newest first, then by name. Both apply, in the order she
    /// gave them.
    #[test]
    fn multiple_fields_keep_their_order() {
        assert_eq!(
            parsed(Some("-created_at, name")),
            [
                Sort::descending(Field::CreatedAt),
                Sort::ascending(Field::Name)
            ]
        );
    }

    /// A field named twice is sorted only the first way it was asked for.
    #[test]
    fn duplicate_field_keeps_first_occurrence() {
        assert_eq!(parsed(Some("name,-name")), [Sort::ascending(Field::Name)]);
    }

    /// Ann sorts names from A to Z and then from Z to A. Ascending keeps
    /// "Ann" before "Bob"; descending puts "Bob" first.
    #[test]
    fn apply_keeps_ascending_and_reverses_descending() {
        let ann_then_bob = "Ann".cmp("Bob");

        let ascending = SortDirection::Asc.apply(ann_then_bob);
        let descending = SortDirection::Desc.apply(ann_then_bob);

        assert_eq!((ascending, descending), (Ordering::Less, Ordering::Greater));
    }

    /// An order written out as a query string parses back to the same
    /// order, which is how a cursor recognises the sort it was made for.
    #[test]
    fn an_order_written_out_parses_back_to_itself() {
        let order = SortOrder::<Field>::parse(Some("-created_at, +name")).unwrap();

        let written = order.to_string();

        assert_eq!(written, "-created_at,name");
        assert_eq!(parsed(Some(&written)), order.terms());
    }

    /// An unknown sort field is rejected by name, with a supported field
    /// included in the error message.
    #[test]
    fn unknown_token_is_rejected() {
        let err = SortOrder::<Field>::parse(Some("name,bogus")).unwrap_err();
        assert_eq!(err.token(), "bogus");
        assert!(err.to_string().contains("created_at"));
    }
}
