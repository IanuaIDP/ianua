//! The runtime resources made from the catalog: one Fluent file per
//! language, its messages grouped by topic, and translated copies of the
//! mail and page templates.
//!
//! Every file below a language folder is generated. Writing replaces what
//! changed and removes what the catalog no longer produces; checking
//! refuses any difference.

mod pattern;
mod verify;

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use self::pattern::Segment;
use crate::catalog::{Catalog, Evidence, Message, MessageKey, Syntax};
use crate::collect::{TEMPLATES, files};
use crate::error::{Error, Result, io_at};
use crate::language::Language;

/// The first lines of every generated Fluent file.
const HEADER: &str = "# Generated by ianua-translate from crates/ianua-translate/catalog.json.\n# Edit the catalog and run write-fluent; changes made here are overwritten.\n";

/// The one Fluent file each language's messages are written to.
const MESSAGES_FILE: &str = "messages.ftl";

/// Where a template subject is written, beside its template's bodies.
const SUBJECT_EXTENSION: &str = "subject";

/// Every generated file, by its path below the locales folder.
#[derive(Debug, PartialEq, Eq)]
pub(crate) struct Locales {
    files: BTreeMap<PathBuf, String>,
}

/// Where one message is written.
#[derive(Clone, Copy)]
enum Placement<'a> {
    /// A Fluent message under its key, in the key's topic file.
    Fluent(&'a MessageKey),
    /// A whole template file at this path below `templates/`.
    Template(&'a str),
    /// A mail subject for the template with this name below `templates/mail/`.
    Subject(&'a str),
}

impl Locales {
    /// Builds every resource from the catalog and reads each Fluent file
    /// back to prove it says exactly what the catalog does.
    ///
    /// # Errors
    ///
    /// Refuses a message without a key or a place, and any Fluent file
    /// that does not read back as written.
    pub(crate) fn from_catalog(catalog: &Catalog) -> Result<Self> {
        catalog.ensure_keyed()?;
        let mut fluent: BTreeMap<PathBuf, BTreeMap<&MessageKey, Vec<Segment>>> = BTreeMap::new();
        let mut files = BTreeMap::new();
        for message in &catalog.messages {
            let placements = placements(message)?;
            for ((language, text), placement) in translated(message)
                .flat_map(|translation| placements.iter().map(move |place| (translation, *place)))
            {
                let Placement::Fluent(key) = placement else {
                    files.insert(placement.path(language), text.to_owned());
                    continue;
                };
                let segments = pattern::segments(text, message.syntax);
                fluent
                    .entry(placement.path(language))
                    .or_default()
                    .insert(key, segments);
            }
        }
        for (path, values) in fluent {
            let resource = resource(&values);
            ensure_reads_back(&path, &resource, &values)?;
            files.insert(path, resource);
        }
        Ok(Self { files })
    }

    /// How many files there are.
    pub(crate) fn len(&self) -> usize {
        self.files.len()
    }

    /// Writes every file that differs and removes generated files the
    /// catalog no longer produces. Returns how many files changed.
    ///
    /// # Errors
    ///
    /// Returns the first file that cannot be read, written or removed.
    pub(crate) fn write(&self, out: &Path) -> Result<usize> {
        let mut changed = 0;
        for (relative, text) in &self.files {
            let path = out.join(relative);
            if fs::read_to_string(&path).is_ok_and(|current| current == *text) {
                continue;
            }
            let parent = path.parent().unwrap_or(out);
            fs::create_dir_all(parent).map_err(io_at(parent))?;
            fs::write(&path, text).map_err(io_at(&path))?;
            changed += 1;
        }
        for stale in self.stale(out)? {
            let path = out.join(stale);
            fs::remove_file(&path).map_err(io_at(&path))?;
            changed += 1;
        }
        Ok(changed)
    }

    /// Refuses a missing, changed or leftover file below the locales folder.
    ///
    /// # Errors
    ///
    /// Names the first file that differs from what the catalog produces.
    pub(crate) fn ensure_current(&self, out: &Path) -> Result<()> {
        for (relative, text) in &self.files {
            let path = out.join(relative);
            if !fs::read_to_string(&path).is_ok_and(|current| current == *text) {
                return Err(Error::StaleFluent(path.display().to_string()));
            }
        }
        match self.stale(out)?.into_iter().next() {
            Some(stale) => Err(Error::StaleFluent(out.join(stale).display().to_string())),
            None => Ok(()),
        }
    }

    /// Generated files on disk that the catalog no longer produces.
    fn stale(&self, out: &Path) -> Result<Vec<PathBuf>> {
        let mut existing = Vec::new();
        for language in Language::ALL {
            let directory = out.join(folder(language));
            if directory.is_dir() {
                files(
                    &directory,
                    &["ftl", "html", "txt", SUBJECT_EXTENSION],
                    &mut existing,
                )?;
            }
        }
        let stale = existing
            .into_iter()
            .filter_map(|path| path.strip_prefix(out).ok().map(Path::to_path_buf))
            .filter(|relative| !self.files.contains_key(relative))
            .collect();
        Ok(stale)
    }
}

/// The languages a message has text for. English templates and subjects
/// stay where the source keeps them.
fn translated(message: &Message) -> impl Iterator<Item = (Language, &str)> {
    let source_kept_in_place = message.syntax == Syntax::MiniJinja;
    Language::ALL
        .into_iter()
        .filter(move |language| !(source_kept_in_place && *language == Language::English))
        .filter_map(|language| Some((language, message.text(language)?)))
}

/// Every file a message is written to: its key's topic file, or each
/// template and each mail that shares this exact template text or subject.
fn placements(message: &Message) -> Result<Vec<Placement<'_>>> {
    if message.syntax != Syntax::MiniJinja {
        let key = message
            .key
            .as_ref()
            .ok_or_else(|| Error::MissingKey(message.id.clone()))?;
        return Ok(vec![Placement::Fluent(key)]);
    }
    let placements: Vec<_> = message
        .occurrences
        .iter()
        .filter_map(|occurrence| match occurrence.evidence {
            Evidence::Template => occurrence
                .path
                .strip_prefix(TEMPLATES)
                .map(|path| Placement::Template(path.trim_start_matches('/'))),
            Evidence::Subject => Some(Placement::Subject(&occurrence.context)),
            _ => None,
        })
        .collect();
    if placements.is_empty() {
        return Err(Error::Fluent {
            file: message.id.clone(),
            detail: "a template message is neither a template file nor a mail subject".to_owned(),
        });
    }
    Ok(placements)
}

impl Placement<'_> {
    /// The file this message is written to for one language.
    fn path(self, language: Language) -> PathBuf {
        let templates = folder(language).join("templates");
        match self {
            Self::Fluent(_) => folder(language).join(MESSAGES_FILE),
            Self::Template(path) => templates.join(path),
            Self::Subject(name) => templates
                .join("mail")
                .join(format!("{name}.{SUBJECT_EXTENSION}")),
        }
    }
}

fn folder(language: Language) -> PathBuf {
    PathBuf::from(language.tag())
}

/// One language's Fluent file: the header, then each message in key
/// order, every topic opened by a group comment naming it.
fn resource(values: &BTreeMap<&MessageKey, Vec<Segment>>) -> String {
    let mut resource = String::from(HEADER);
    let mut topic = None;
    for (key, segments) in values {
        if topic != Some(key.topic()) {
            topic = Some(key.topic());
            resource.push_str(&format!("\n## {}\n", key.topic()));
        }
        resource.push_str(&format!("\n{key} = {}\n", pattern::value(segments)));
    }
    resource
}

/// Parses a generated file and refuses it unless every message reads back
/// as exactly the pieces it was written from, and nothing else is in it.
fn ensure_reads_back(
    path: &Path,
    resource: &str,
    expected: &BTreeMap<&MessageKey, Vec<Segment>>,
) -> Result<()> {
    let file = path.display().to_string();
    let read = verify::read_back(&file, resource)?;
    let differing = expected
        .iter()
        .find(|(key, segments)| read.get(key.as_str()) != Some(*segments));
    if let Some((key, _)) = differing {
        return Err(Error::Fluent {
            file,
            detail: format!("{key} reads back differently from the catalog"),
        });
    }
    if read.len() != expected.len() {
        return Err(Error::Fluent {
            file,
            detail: "the file holds messages the catalog does not".to_owned(),
        });
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::catalog::Occurrence;

    fn keyed(english: &str, syntax: Syntax, key: &str) -> Message {
        let mut message = Message::new(
            english.to_owned(),
            syntax,
            Occurrence {
                path: "crates/ianua-app/src/use_cases/people/invite.rs".to_owned(),
                line: 1,
                column: 1,
                context: "invite".to_owned(),
                evidence: Evidence::CustomerError,
                keyed: None,
            },
        );
        message.key = Some(MessageKey::try_from(key.to_owned()).unwrap());
        message
    }

    fn catalog() -> Catalog {
        let mut catalog = Catalog::new();
        let mut invite = keyed("Invite {name} to {}", Syntax::RustFormat, "people-invite");
        invite
            .translations
            .insert(Language::German, Some("{name} zu {} einladen".to_owned()));
        let mut subject = keyed(
            "Reset your password",
            Syntax::MiniJinja,
            "mail-subject-reset",
        );
        subject.occurrences[0].evidence = Evidence::Subject;
        subject.occurrences[0].context = "sign_in/password_reset".to_owned();
        subject
            .translations
            .insert(Language::German, Some("Passwort zurücksetzen".to_owned()));
        catalog.messages = vec![invite, subject];
        catalog
    }

    /// A message lands in its language's file under its topic, with Fluent variables.
    #[test]
    fn messages_are_written_per_language_under_their_topic() {
        let locales = Locales::from_catalog(&catalog()).unwrap();
        let german = &locales.files[Path::new("de/messages.ftl")];
        assert!(
            german.ends_with("\n## people\n\npeople-invite = { $name } zu { $arg0 } einladen\n")
        );
        let english = &locales.files[Path::new("en/messages.ftl")];
        assert!(english.ends_with("\npeople-invite = Invite { $name } to { $arg0 }\n"));
        assert!(!locales.files.contains_key(Path::new("fr/messages.ftl")));
    }

    /// Two mails sharing an English subject each receive the German subject at their own path.
    #[test]
    fn a_shared_subject_is_written_for_every_mail() {
        let mut catalog = catalog();
        let mut second = catalog.messages[1].occurrences[0].clone();
        second.context = "organization/verification".to_owned();
        catalog.messages[1].occurrences.push(second);
        let locales = Locales::from_catalog(&catalog).unwrap();
        for name in ["sign_in/password_reset", "organization/verification"] {
            let path = PathBuf::from(format!("de/templates/mail/{name}.subject"));
            assert_eq!(locales.files[&path], "Passwort zurücksetzen");
        }
    }

    /// A translated subject is written beside its template; English stays in the source.
    #[test]
    fn subjects_are_written_beside_their_templates() {
        let locales = Locales::from_catalog(&catalog()).unwrap();
        let path = Path::new("de/templates/mail/sign_in/password_reset.subject");
        assert_eq!(locales.files[path], "Passwort zurücksetzen");
        assert!(
            !locales
                .files
                .keys()
                .any(|path| path.starts_with("en/templates"))
        );
    }

    /// Writing twice changes nothing the second time, and the check passes.
    #[test]
    fn writing_is_idempotent_and_checked() {
        let directory = tempfile::tempdir().unwrap();
        let locales = Locales::from_catalog(&catalog()).unwrap();
        assert_eq!(locales.write(directory.path()).unwrap(), locales.len());
        assert_eq!(locales.write(directory.path()).unwrap(), 0);
        locales.ensure_current(directory.path()).unwrap();
    }

    /// An extra resource fails the freshness check, and writing the catalog removes that file.
    #[test]
    fn leftover_files_are_removed_and_refused_by_the_check() {
        let directory = tempfile::tempdir().unwrap();
        let locales = Locales::from_catalog(&catalog()).unwrap();
        locales.write(directory.path()).unwrap();
        let leftover = directory.path().join("de/removed.ftl");
        fs::write(&leftover, "old = text\n").unwrap();
        assert!(matches!(
            locales.ensure_current(directory.path()),
            Err(Error::StaleFluent(_))
        ));
        assert_eq!(locales.write(directory.path()).unwrap(), 1);
        assert!(!leftover.exists());
    }

    /// Replacing generated German text with a hand edit fails the freshness check.
    #[test]
    fn an_edited_file_fails_the_check() {
        let directory = tempfile::tempdir().unwrap();
        let locales = Locales::from_catalog(&catalog()).unwrap();
        locales.write(directory.path()).unwrap();
        fs::write(
            directory.path().join("de/messages.ftl"),
            "people-invite = x\n",
        )
        .unwrap();
        assert!(locales.ensure_current(directory.path()).is_err());
    }

    /// A missing message key prevents generation of the catalog's locale resources.
    #[test]
    fn a_message_without_a_key_is_refused() {
        let mut catalog = catalog();
        catalog.messages[0].key = None;
        assert!(matches!(
            Locales::from_catalog(&catalog),
            Err(Error::MissingKey(_))
        ));
    }
}
