function countryName(code: string, locale: string) {
  try {
    const names = new Intl.DisplayNames([locale], { type: 'region' });

    return names.of(code) ?? code;
  } catch {
    return code;
  }
}

const optionsByLocale = new Map<string, SelectOption[]>();

/** The countries as select options, named and sorted in `locale`. */
export function getCountryOptions(locale: string): SelectOption[] {
  const cached = optionsByLocale.get(locale);

  if (cached) {
    return cached;
  }

  const options = COUNTRY_CODES.map((code) => ({
    label: countryName(code, locale),
    value: code,
  })).sort((left, right) => left.label.localeCompare(right.label, locale));

  optionsByLocale.set(locale, options);

  return options;
}
